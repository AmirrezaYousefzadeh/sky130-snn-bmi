#!/usr/bin/env python3
"""Round 10: state-dependent internal power of a macro (SRAM22) under a stopped clock.

The SRAM liberty gives the clock-pin energy per state of the control pins (when "we&ce", "!we&ce", ...). OpenSTA weights these
tables with the time-averaged duty of ce and we and assumes them independent of the clock toggling. In a real-time window the
clock runs for a few per cent of the time and ce is low whenever the clock is stopped, so the read energy is weighted with
P(ce) ~ 0.08 instead of P(ce | clock running) ~ 0.95: the macro power comes out ~ 10x too low. This script writes, for every
instance of the macro cells, set_power_activity commands for the pins named in the when-conditions with the duty conditioned on
the macro clock running (duty_cond = (duty - v_idle (1 - d_clk)) / d_clk, d_clk = activity(clk pin) / 2 = fraction of cycles with
a macro clock edge, v_idle = the pin's value while the clock is stopped, inferred from the feasibility of the two values), and -
in --compare mode - reports the difference between the standard run and the run with these commands (power/power_toggles_sta.tcl,
env EXTRA_ACT_TCL) as a separately reported correction.
Usage: macro_state_correction.py gen <out_dir> <netlist.v> <liberty.lib> [--cells sram22_2048x32m8w8] -o <out_dir>/macro_cond.tcl [--json <file>]
       macro_state_correction.py compare <out_std> <out_cond> <netlist.v> [--cells ...] [--json <file>]"""
import re, sys, json, argparse
ap = argparse.ArgumentParser(); ap.add_argument("mode", choices=("gen", "compare")); ap.add_argument("args", nargs="+")
ap.add_argument("--cells", default="sram22_2048x32m8w8"); ap.add_argument("-o", default=None); ap.add_argument("--json", default=None); ap.add_argument("--clk-pin", default="clk")
a = ap.parse_args(); cells = a.cells.split(",")

def instances(netlist):
    nl = open(netlist, errors="ignore").read(); res = {}
    for m in re.finditer(r"^\s*([A-Za-z_][\w$]*)\s+(\\?\S+)\s*\((.*?)\);", nl, flags=re.S | re.M):
        if m.group(1) in cells: res[m.group(2).lstrip("\\")] = (m.group(1), dict(re.findall(r"\.(\w+)\(\s*([^()]*?)\s*\)", m.group(3))))
    return res

def when_pins(liberty, cell):
    """pins referenced by the when-conditions of the internal_power groups of <cell>"""
    s = open(liberty, errors="ignore").read(); i = s.find(f"cell ({cell})"); i = i if i >= 0 else s.find(f'cell ("{cell}")')
    if i < 0: sys.exit(f"cell {cell} not in {liberty}")
    j = s.find("\n  cell (", i + 10); j = j if j > 0 else s.find('\n  cell ("', i + 10); body = s[i:j if j > 0 else len(s)]
    pins = set()
    for blk in re.finditer(r"internal_power\s*\(\)\s*\{(.*?)\n\s*\}", body, flags=re.S):
        for w in re.findall(r'when\s*:\s*"([^"]*)"', blk.group(1)): pins.update(re.findall(r"[A-Za-z_]\w*(?:\[\d+\])?", w))
    return sorted(pins)

def activities(act_tcl):
    d = {}
    for line in open(act_tcl, errors="ignore"):
        m = re.match(r"__(?:top|pin)_act \{(.+?)\} (\S+) (\S+)", line)
        if m: d[m.group(1).replace("\\", "")] = (float(m.group(2)), float(m.group(3)))
    return d

def rpt(path):
    d = {}
    for line in open(path, errors="ignore"):
        f = line.split()
        if len(f) >= 5:
            try: d[f[4].lstrip("\\")] = tuple(float(x) for x in f[:4])
            except ValueError: pass
    return d

if a.mode == "gen":
    out_dir, netlist, liberty = a.args[:3]; inst = instances(netlist)
    if not inst: sys.exit(f"no instance of {cells} in {netlist}")
    act = activities(f"{out_dir}/activity.tcl"); L = ["# generated by power/macro_state_correction.py: macro state pins with the duty conditioned on the macro clock running"]; info = {}
    for name, (cell, pins) in inst.items():
        wp = when_pins(liberty, cell); clk_net = pins.get(a.clk_pin)
        clk_act = act.get(f"{name}/{a.clk_pin}") or act.get(clk_net or "")
        if not clk_act: print(f"WARNING: no activity for the clock pin of {name}"); continue
        d_clk = clk_act[0] / 2.0; rec = {"cell": cell, "clk_net": clk_net, "clk_activity": clk_act[0], "d_clk": d_clk, "pins": {}}
        for p in wp:
            if p not in pins: continue
            net = pins[p]; pa = act.get(f"{name}/{p}") or act.get(net)
            if not pa: print(f"WARNING: no activity for {name}/{p} ({net})"); continue
            duty = pa[1]
            if duty <= d_clk * (1 + 1e-6) + 1e-9: v_idle, cond = 0, duty / d_clk if d_clk > 0 else duty
            elif duty >= 1 - d_clk * (1 + 1e-6) - 1e-9: v_idle, cond = 1, (duty - (1 - d_clk)) / d_clk if d_clk > 0 else duty
            else: v_idle, cond = None, min(1.0, duty / d_clk if d_clk > 0 else duty); print(f"WARNING: {name}/{p}: duty {duty:.6f} is neither <= d_clk {d_clk:.6f} nor >= 1 - d_clk: the pin changes while the clock is stopped; v_idle = 0 assumed")
            cond = min(max(cond, 0.0), 1.0)
            L.append(f"set_power_activity -pins {{{name}/{p}}} -activity {pa[0]:.6g} -duty {cond:.6f}")
            rec["pins"][p] = {"net": net, "activity": pa[0], "duty_window": duty, "v_idle": v_idle, "duty_conditional": cond}
        info[name] = rec
    open(a.o or f"{out_dir}/macro_cond.tcl", "w").write("\n".join(L) + "\n")
    if a.json: json.dump(info, open(a.json, "w"), indent=1)
    for n, r in info.items(): print(f"{n} ({r['cell']}): d_clk {r['d_clk']:.6f}; " + "; ".join(f"{p}: duty {v['duty_window']:.6f} -> {v['duty_conditional']:.6f} (idle {v['v_idle']})" for p, v in r["pins"].items()))
else:
    out_std, out_cond, netlist = a.args[:3]; inst = instances(netlist)
    A = rpt(f"{out_std}/power_vcd_by_instance.rpt"); B = rpt(f"{out_cond}/power_vcd_by_instance.rpt")
    tot = lambda d: [sum(v[k] for v in d.values()) for k in range(4)]
    ta, tb = tot(A), tot(B); res = {"instances": {}, "total_std_W": dict(zip(("internal", "switching", "leakage", "total"), ta)), "total_cond_W": dict(zip(("internal", "switching", "leakage", "total"), tb))}
    dm = 0.0
    for n in inst:
        if n in A and n in B:
            res["instances"][n] = {"std_W": dict(zip(("internal", "switching", "leakage", "total"), A[n])), "cond_W": dict(zip(("internal", "switching", "leakage", "total"), B[n])), "added_W": B[n][3] - A[n][3]}
            dm += B[n][3] - A[n][3]
    res["added_W"] = tb[3] - ta[3]; res["added_macro_W"] = dm; res["added_outside_macros_W"] = (tb[3] - ta[3]) - dm
    try: res["macro_cond"] = json.load(open(f"{out_std}/macro_cond.json"))
    except Exception: pass
    if a.json: json.dump(res, open(a.json, "w"), indent=1)
    for n, r in res["instances"].items(): print(f"{n}: total {r['std_W']['total']*1e6:.4f} -> {r['cond_W']['total']*1e6:.4f} uW (internal {r['std_W']['internal']*1e6:.4f} -> {r['cond_W']['internal']*1e6:.4f})")
    print(f"macro state correction: +{res['added_W']*1e6:.4f} uW on the total (macros +{dm*1e6:.4f}, elsewhere {res['added_outside_macros_W']*1e6:+.6f})")
